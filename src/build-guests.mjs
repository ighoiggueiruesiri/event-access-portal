// Converts the guest spreadsheet into the data file the pass reads.
//
//   npm i -D xlsx
//   node build-guests.mjs boa_table.xlsx src/guests.js
//
// Re-run it whenever you update the sheet. Columns used:
//   S/N, Name, Category, Table   (Phone Number is deliberately NOT exported:
//   anything in guests.js ships inside the public JavaScript bundle.)

import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';
import XLSX from 'xlsx';

const [input = 'boa_table.xlsx', output = 'guests.js'] = process.argv.slice(2);

const wb = XLSX.read(readFileSync(input));
const rows = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { defval: null });

const clean = (v) => {
  if (v === null || v === undefined) return '';
  return String(v).replace(/\s+/g, ' ').trim();
};
const toSerial = (v) => {
  const n = Number(clean(v));
  return Number.isInteger(n) && n > 0 ? n : null;
};

// Highest serial number already used, so provisional ones never collide.
const taken = new Set();
let max = 0;
for (const r of rows) {
  const n = toSerial(r['S/N']);
  if (n) max = Math.max(max, n);
}
let nextFree = max + 1;

const guests = [];
const warnings = [];

rows.forEach((r, i) => {
  const sheetRow = i + 2; // header is row 1
  const name = clean(r['Name']);

  if (!name) {
    warnings.push(`Row ${sheetRow}: no name, skipped (${clean(r['Category']) || 'no category'}).`);
    return;
  }

  let serial = toSerial(r['S/N']);
  if (!serial) {
    serial = nextFree++;
    warnings.push(`Row ${sheetRow}: "${name}" has no S/N, given provisional HT-${String(serial).padStart(3, '0')}.`);
  } else if (taken.has(serial)) {
    const dup = serial;
    serial = nextFree++;
    warnings.push(`Row ${sheetRow}: "${name}" repeats S/N ${dup}, given provisional HT-${String(serial).padStart(3, '0')}.`);
  }
  taken.add(serial);

  guests.push({
    id: `HT-${String(serial).padStart(3, '0')}`,
    name,
    category: clean(r['Category']) || 'Guest',
    table: clean(r['Table']) || null,
  });
});

const j = (v) => JSON.stringify(v);
const lines = guests.map(
  (g) => `  { id: ${j(g.id)}, name: ${j(g.name)}, category: ${j(g.category)}, table: ${j(g.table)} },`
);

writeFileSync(
  output,
  `// AUTO-GENERATED by build-guests.mjs from ${basename(input)}. Do not edit by hand.\n` +
    `// Phone numbers are intentionally left out; this file is public in the built site.\n` +
    `export const registeredGuests = [\n${lines.join('\n')}\n];\n`
);

console.log(`Wrote ${guests.length} guests to ${output}`);
if (warnings.length) {
  console.log(`\n${warnings.length} thing(s) to check in the sheet:`);
  warnings.forEach((w) => console.log('  - ' + w));
}
